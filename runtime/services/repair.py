"""swarm_engine/services/repair.py

RepairService: the canonical product API for repair evidence and
admission.

Prior missions drove repairs through test drivers that called
``org.review.verify_repair`` / ``org.review.admit_repair`` directly.
This service is the product wiring agents must use instead: it accepts
JSON-serializable case descriptions over the service boundary, builds
the in-process verification artifacts (``Case`` objects, a minimal
spec), and delegates to the ReviewBoard -- the ONLY path whose verdict
can authorize admission. It adds no trust of its own: every guarantee
(confused-deputy refusal, verdict binding to exact post bytes,
admission derived from the stored verdict only) lives in
``ReviewBoard`` and the caller-authorization layer, which this service
does not weaken or bypass.

Honest bounds (read before extending):
  * ``predicate`` cases are in-process-only: a ``Case`` predicate is a
    Python callable and cannot cross a JSON service boundary. A case
    dict containing ``"predicate"`` is refused outright -- silently
    dropping it would weaken the verification the caller thinks it
    asked for. Use ``expect`` / ``must_fail`` across the boundary.
  * Case args and expectations must be JSON-serializable: they are
    shipped to the isolated subprocess runner as a JSON payload. The
    service validates this up front and refuses non-serializable
    values with a clear error instead of failing deep in the runner.
  * The spec's examples are derived from the submitted positive cases
    (args, expect pairs). The adversary, novelty probes, and held-out
    generalisation checks are still generated by the REAL
    IndependentValidator from that spec -- the service does not
    pre-answer them.
  * Reads (get_repair / list_repairs) require an authenticated caller
    (any live agent); the engine handle authenticates too. They expose
    repair records and verdict standing only -- no mutation.
"""
from __future__ import annotations

import ast
import json
from typing import Any, Dict, List, Optional

from swarm_engine.acquisition.semantic import Case
from swarm_engine.agent_org.store import digest, now
from swarm_engine.governance.caller_authorization import (
    AgentDirectory, AuthorizationError, CallerContext)


_CASE_KINDS = ("positive", "negative", "edge")


class RepairSpec:
    """Minimal verification spec built from the defect signature.

    input_names: entrypoint parameter names (from the defect signature,
    else AST-derived from the entrypoint in the repaired code, else the
    union of case arg keys). description: human-readable statement of
    what is being verified. examples: (args, expect) pairs from the
    submitted positive cases -- the source the Adversary draws held-out
    generalisation cases and novelty probes from.
    """

    def __init__(self, input_names: List[str], description: str,
                 examples: List[tuple]):
        self.input_names = list(input_names)
        self.description = description
        self.examples = list(examples)


def _entrypoint_params(post_code: str, entrypoint: str) -> List[str]:
    """AST-derive the entrypoint's parameter names from the repaired code."""
    try:
        tree = ast.parse(post_code or "")
    except SyntaxError:
        return []
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == entrypoint:
            return [a.arg for a in node.args.args]
    return []


def _case_from_json(case_dict: Dict[str, Any]) -> Case:
    """Build an in-process Case from its JSON-serializable description.

    Refuses (ValueError) when the description carries a predicate --
    callables cannot cross the service boundary -- or when args/expect
    are not JSON-serializable (the subprocess runner ships them as JSON).
    """
    if not isinstance(case_dict, dict):
        raise ValueError(
            f"repair case must be a dict, got {type(case_dict).__name__}")
    if "predicate" in case_dict:
        raise ValueError(
            "repair case 'predicate' is in-process-only: a predicate is a "
            "Python callable and cannot cross the JSON service boundary. "
            "Express the expectation with 'expect' and/or 'must_fail' "
            "instead; the case was refused, not silently weakened.")
    args = case_dict.get("args", {})
    if not isinstance(args, dict):
        raise ValueError(
            f"repair case 'args' must be a dict, got {type(args).__name__}")
    kind = case_dict.get("kind", "positive")
    if kind not in _CASE_KINDS:
        raise ValueError(
            f"repair case 'kind' must be one of {_CASE_KINDS}, got {kind!r}")
    must_fail = bool(case_dict.get("must_fail", False))
    expect = case_dict.get("expect")
    label = str(case_dict.get("label", ""))
    try:
        json.dumps({"args": args, "expect": expect})
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"repair case args/expect must be JSON-serializable for the "
            f"subprocess boundary: {exc}")
    return Case(args=dict(args), expect=expect, label=label, kind=kind,
                must_fail=must_fail)


def _build_spec(defect_signature: Dict[str, Any], entrypoint: str,
                post_code: str, cases: List[Case]) -> RepairSpec:
    family = defect_signature.get("family", "unknown")
    input_names = defect_signature.get("input_names")
    if not input_names:
        input_names = _entrypoint_params(post_code, entrypoint)
    if not input_names:
        seen: List[str] = []
        for case in cases:
            for key in case.args:
                if key not in seen:
                    seen.append(key)
        input_names = seen
    description = (
        f"repair evidence for defect family {family!r} at "
        f"{defect_signature.get('file', '?')}:"
        f"{defect_signature.get('function', '?')} "
        f"(observed: {defect_signature.get('observed', 'unspecified')}); "
        f"review entrypoint {entrypoint!r} must satisfy the submitted cases")
    examples = [(dict(c.args), c.expect) for c in cases
                if not c.must_fail and c.expect is not None]
    return RepairSpec(list(input_names), description, examples)


class RepairService:
    """Canonical repair evidence/admission API over a ReviewBoard.

    org: a RemorOrganization (uses org.review and org.store).
    agents: an AgentDirectory, used for read-path authentication.
    """

    def __init__(self, org: Any, agents: AgentDirectory):
        if org is None or getattr(org, "review", None) is None:
            raise ValueError(
                "RepairService requires an org exposing .review")
        if not isinstance(agents, AgentDirectory):
            raise ValueError(
                "RepairService requires an AgentDirectory for read-path auth")
        self.org = org
        self.agents = agents

    # -- submission / admission --------------------------------------

    def submit_repair(self, *, repair_id: str, agent_id: str,
                      defect_signature: Dict[str, Any], diagnosis: str,
                      pre_code: str, post_code: str, entrypoint: str,
                      cases: List[Dict[str, Any]], caller: Any) -> Dict[str, Any]:
        """Submit a repair for independent verification.

        Builds in-process Case objects from the JSON case descriptions
        (predicate cases refused -- see module docstring), builds the
        minimal spec from the defect signature, and delegates to
        ReviewBoard.verify_repair -- the only verification path whose
        verdict can authorize admission. Returns repair_id, whether the
        independent verdict admitted, the verdict execution_id, and the
        verdict reasons.
        """
        if not repair_id:
            raise ValueError("submit_repair: empty repair_id")
        if not agent_id:
            raise ValueError("submit_repair: empty agent_id")
        if not isinstance(defect_signature, dict):
            raise ValueError("submit_repair: defect_signature must be a dict")
        if not isinstance(cases, (list, tuple)) or not cases:
            raise ValueError("submit_repair: cases must be a non-empty list")
        if not post_code:
            raise ValueError("submit_repair: empty post_code")
        spec_cases = [_case_from_json(c) for c in cases]
        spec = _build_spec(defect_signature, entrypoint or "selftest",
                           post_code, spec_cases)
        verdict = self.org.review.verify_repair(
            repair_id=repair_id, agent_id=agent_id,
            defect_signature=dict(defect_signature),
            diagnosis=diagnosis or "",
            pre_code=pre_code or "", post_code=post_code,
            entrypoint=entrypoint, spec=spec, cases=spec_cases,
            caller=caller)
        rec = self.org.review.get_repair_record(repair_id)
        # Byte retention for the submit -> admit gap: the exact submitted
        # post bytes persist in the chained ao_repair_submissions table so
        # a later admit_versioned / apply / rollback (a separate product
        # call, possibly a separate process) can resolve them. The bytes
        # are untrusted-by-construction -- get_repair() only surfaces
        # them when digest(post_code) == the record's post_digest (the
        # verdict-bound digest); a mismatch omits the key and every
        # downstream consumer refuses.
        post_digest = digest(post_code)
        self.org.store.insert("ao_repair_submissions", {
            "submission_id": "sub_" + digest(
                repair_id + post_digest + now())[:16],
            "repair_id": repair_id, "post_code": post_code,
            "post_digest": post_digest, "submitted_by": agent_id,
            "created_at": now()})
        return {
            "repair_id": repair_id,
            "admitted": bool(verdict.admitted),
            "execution_id": rec["verdict_execution_id"],
            "reasons": list(verdict.reasons),
        }

    def admit_repair(self, repair_id: str, caller: Any) -> Dict[str, Any]:
        """Admit an independently verified repair.

        Delegates to ReviewBoard.admit_repair: the caller must hold
        'agent:repair_apply', a stored admitted verdict must exist for
        the EXACT post bytes, and double admission is refused. Trust is
        derived from the stored verdict row only.
        """
        decision_id = self.org.review.admit_repair(repair_id, caller=caller)
        return {"repair_id": repair_id, "decision_id": decision_id}

    # -- governed reads -----------------------------------------------

    def _read_auth(self, caller: Any, op_name: str) -> str:
        """Authenticate any live agent (the engine handle works too).

        Raises AuthorizationError for missing, malformed, forged, or
        destroyed credentials -- reads expose repair records and verdict
        standing to authenticated parties only.
        """
        try:
            ctx = CallerContext.from_pair(caller)
        except AuthorizationError as exc:
            raise AuthorizationError(
                f"unauthenticated: {op_name} refused ({exc})")
        if not self.agents.authenticate(ctx.agent_id, ctx.token):
            raise AuthorizationError(
                f"unauthenticated: {op_name} refused (caller credential did "
                f"not authenticate: unknown agent, forged credential, wrong "
                f"token, or destroyed agent)")
        return ctx.agent_id

    def _verdict_standing(self, record: Dict[str, Any]) -> Dict[str, Any]:
        """Latest verdict standing for a repair record: admitted or not,
        and the execution_id of the latest verdict row (None when no
        verdict row exists for the recorded post bytes)."""
        vrow = self.org.review.latest_artifact_verdict(
            record.get("post_digest", ""), "repair")
        if vrow is None or vrow.get("artifact_ref") != record.get("repair_id"):
            return {"admitted": False, "execution_id": None}
        return {"admitted": vrow.get("admitted") == "1",
                "execution_id": vrow.get("execution_id")}

    def get_repair(self, repair_id: str, caller: Any) -> Dict[str, Any]:
        """Governed read of one repair record plus its latest verdict
        standing. Caller must authenticate (any live agent). Raises
        KeyError for an unknown repair_id.

        When the latest submission's bytes reproduce the record's
        verdict-bound post_digest, the exact verified post bytes are
        included as "post_code" (this is what RepairLifecycle resolves
        for versioned admission / apply / rollback). A mismatch -- or no
        submission -- omits the key: bytes are never trusted on their
        own, only via the digest binding.
        """
        self._read_auth(caller, "get_repair")
        record = dict(self.org.review.get_repair_record(repair_id))
        record["standing"] = self._verdict_standing(record)
        sub = self.org.store.latest("ao_repair_submissions", "repair_id",
                                    repair_id)
        if (sub is not None
                and digest(sub.get("post_code") or "")
                == record.get("post_digest")):
            record["post_code"] = sub["post_code"]
        return record

    def list_repairs(self, caller: Any,
                     defect_family: Optional[str] = None) -> List[Dict[str, Any]]:
        """Governed read of repair records: the latest row per repair_id,
        optionally filtered by defect family. Caller must authenticate
        (any live agent)."""
        self._read_auth(caller, "list_repairs")
        latest: Dict[str, Dict[str, Any]] = {}
        for row in self.org.store.rows("ao_repair_records"):
            rid = row.get("repair_id")
            if rid is None:
                continue
            prev = latest.get(rid)
            if prev is None or row.get("seq", 0) > prev.get("seq", 0):
                latest[rid] = row
        out: List[Dict[str, Any]] = []
        for rid in sorted(latest):
            record = dict(latest[rid])
            if defect_family is not None:
                try:
                    sig = json.loads(record.get("defect_signature_json")
                                     or "{}")
                except (TypeError, ValueError):
                    sig = {}
                if not isinstance(sig, dict) or \
                        sig.get("family") != defect_family:
                    continue
            record["standing"] = self._verdict_standing(record)
            out.append(record)
        return out
